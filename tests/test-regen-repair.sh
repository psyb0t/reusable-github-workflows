#!/usr/bin/env bash
# Run: bash tests/test-regen-repair.sh. No token or network required.
set -euo pipefail

root="$(cd -- "${BASH_SOURCE[0]%/*}/.." && pwd)"
work="$(mktemp -d /tmp/regen-repair.XXXXXX)"
readonly root work
trap 'printf "Fixture retained: %s\n" "${work}"' EXIT
trap 'printf "Test failed at line %s\n" "${LINENO}" >&2' ERR

log() {
	jq -cn --arg time "$(date -u +%FT%TZ)" --arg level "$1" \
		--arg file "${BASH_SOURCE[0]##*/}" --argjson line "${BASH_LINENO[0]}" \
		--arg func "${FUNCNAME[1]:-main}" --arg msg "$2" \
		'{time:$time,level:$level,file:$file,line:$line,func:$func,msg:$msg}' >&2
}

mkdir "${work}/repo" "${work}/fix"
cd "${work}/repo"
printf 'broken\n' >toolchain
printf 'https://provider.example/spec.yml\n' >source.txt
# All Git mutations are confined to this disposable fixture script.
printf '%s\n' 'git init -q' \
	'git -c user.name=Fixture -c user.email=fixture@example.invalid add toolchain source.txt' \
	'git -c user.name=Fixture -c user.email=fixture@example.invalid commit -qm baseline' \
	>"${work}/git-update.sh"
bash "${work}/git-update.sh"
export FIX_DIR="${work}/fix" GITHUB_OUTPUT="${work}/output"
export LOG_FILE="${work}/helper.log" ATTEMPT=0
export WRITING_RULES="${root}/scripts/regen-writing-rules.md"
export MAX_DIFF_BYTES=200000 MAX_ATTEMPTS=3

assert_output() {
	grep -Fxq "passed=$1" "${GITHUB_OUTPUT}"
}

run_check() {
	: >"${GITHUB_OUTPUT}"
	bash "${root}/scripts/regen-check.sh"
}

export GENERATE_COMMAND='printf "generation failed\n"; exit 7'
export CHECK_COMMANDS='printf "should not run\n"; exit 0'
run_check
assert_output false
grep -Fq 'generation failed' "${FIX_DIR}/check-0.log"
log INFO 'generation failure reaches repair'

export GENERATE_COMMAND=- CHECK_COMMANDS='grep -qx patched toolchain'
run_check
assert_output false
log INFO 'unchanged security failure reaches repair'

for ATTEMPT in 1 2 3; do
	export ATTEMPT
	bash "${root}/scripts/regen-fix.sh" prepare
	printf '// nolint:security\n' >suppression.go
	printf '// Code generated by fixture. DO NOT EDIT.\n// nolint:security\n' >generated.gen.go
	status=0
	bash "${root}/scripts/regen-fix.sh" guard >"${FIX_DIR}/guard-${ATTEMPT}.log" 2>&1 || status=$?
	test "${status}" -ne 0
	export GUARD_OUTCOME=failure
	run_check
	assert_output false
	grep -Fq 'suppression' "${FIX_DIR}/check-${ATTEMPT}.log"
	if ((ATTEMPT > 1)); then
		grep -Fq 'suppression' "${FIX_DIR}/attempt-${ATTEMPT}/context/check-output.log"
	fi
done
log INFO 'three suppression attempts rejected with corrective history'

status=0
bash "${root}/scripts/regen-fix.sh" guard >"${work}/cumulative.log" 2>&1 || status=$?
test "${status}" -ne 0

printf 'package fixture\n' >suppression.go
printf '// Code generated by fixture. DO NOT EDIT.\npackage fixture\n' >generated.gen.go
printf 'patched\n' >toolchain
RESULT='Patched the fixture toolchain.' bash "${root}/scripts/regen-fix.sh" guard
export GUARD_OUTCOME=success GENERATE_COMMAND='printf "regenerated\n"'
export GUARD_SCRIPT="${root}/scripts/regen-fix.sh"
run_check
assert_output true
grep -Fq regenerated "${FIX_DIR}/check-3.log"
grep -Fxq 'Patched the fixture toolchain.' "${FIX_DIR}/notes-3.md"
log INFO 'valid repair re-runs generation and checks'

export CHECK_COMMANDS=- GENERATE_COMMAND=-
run_check
assert_output true

export CHECK_COMMANDS='printf "mutation\n" > toolchain'
status=0
run_check >"${work}/mutating-check.log" 2>&1 || status=$?
test "${status}" -ne 0
log INFO 'mutating validation remains fatal'

printf 'https://untrusted.example/spec.yml\n' >source.txt
status=0
bash "${root}/scripts/regen-fix.sh" guard >"${work}/source-rejection.log" 2>&1 || status=$?
test "${status}" -ne 0
grep -Fq 'URL' "${work}/source-rejection.log"
log INFO 'unapproved replacement source rejected'

export OFFICIAL_SOURCE_URLS=https://untrusted.example/spec.yml
bash "${root}/scripts/regen-fix.sh" guard
log INFO 'exact caller approval permits a replacement URL'

# New suppression directives created by regeneration must also fail validation.
export CHECK_COMMANDS=true
export GENERATE_COMMAND='printf "// nolint:security\n" > generated.gen.go'
run_check
assert_output false
log INFO 'post-generation suppression rejected'

for marker in 't.Skip("hidden")' '# nosec' '# noqa' '# nosemgrep' '// nolint' 'pytest.mark.skip'; do
	printf '%s\n' "${marker}" >generated.gen.go
	status=0
	bash "${root}/scripts/regen-fix.sh" guard >"${work}/marker.log" 2>&1 || status=$?
	test "${status}" -ne 0
done
printf 'package fixture\n' >generated.gen.go
printf 'exclude_all: true\n' >.semgrepignore
status=0
bash "${root}/scripts/regen-fix.sh" guard >"${work}/protected.log" 2>&1 || status=$?
test "${status}" -ne 0
grep -Fq 'protected paths' "${work}/protected.log"
log INFO 'suppression markers and scanner configuration rejected'

log INFO 'regen repair tests passed'
